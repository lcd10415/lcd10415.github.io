window.SL_applyLang = function (code) {
  const dict = window.SL_I18N[code] || window.SL_I18N.en;
  document.documentElement.lang = code;
  document.title = dict.docTitle;
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", dict.docDesc);
  const ogt = document.querySelector('meta[property="og:title"]');
  if (ogt) ogt.setAttribute("content", dict.brand + " · SimpleLedger");
  const ogd = document.querySelector('meta[property="og:description"]');
  if (ogd) ogd.setAttribute("content", dict.docDesc);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  const brandSub = document.querySelector("[data-i18n-brand-sub]");
  if (brandSub) brandSub.textContent = dict.brandSub;

  const sel = document.getElementById("lang-select");
  if (sel && sel.value !== code) sel.value = code;

  try { localStorage.setItem("sl_lang", code); } catch (_) {}
};

window.SL_detectLang = function () {
  try {
    const saved = localStorage.getItem("sl_lang");
    if (saved && window.SL_I18N[saved]) return saved;
  } catch (_) {}
  const list = (navigator.languages || [navigator.language || "en"]).map(String);
  for (const raw of list) {
    const n = raw.replace("_", "-");
    if (window.SL_I18N[n]) return n;
    const short = n.split("-")[0];
    if (short === "zh") {
      if (/hant|tw|hk|mo/i.test(n)) return "zh-Hant";
      return "zh-Hans";
    }
    if (window.SL_I18N[short]) return short;
  }
  return "en";
};
